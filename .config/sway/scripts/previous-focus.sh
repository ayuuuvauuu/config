#!/usr/bin/env bash
# Keep a short focus-history stack and navigate it with --prev/--next.
# The history contains Sway container IDs, so it works across workspaces.

set -u

STATE_FILE="/tmp/sway-focus-history-${UID}.txt"
STATE_LOCK="/tmp/sway-focus-history-${UID}.lock"
DAEMON_LOCK="/tmp/sway-focus-history-${UID}.daemon.lock"
MAX_HISTORY=8
# A focus command can produce more than one Sway event (especially across
# workspaces). Keep its marker briefly so those events do not rebuild the list.
PENDING_TTL=3

current_container() {
    swaymsg -t get_tree -r 2>/dev/null |
        jq -r '.. | objects | select(.focused == true and (.type == "con" or .type == "floating_con")) | .id' |
        head -n 1
}

container_exists() {
    [[ "$1" =~ ^[0-9]+$ ]] || return 1
    swaymsg -t get_tree -r 2>/dev/null |
        jq -e --argjson id "$1" '
            .. | objects
            | select(.id? == $id and (.type == "con" or .type == "floating_con"))
            | .id
        ' >/dev/null
}

now() {
    date +%s
}

with_state_lock() {
    exec 8>"$STATE_LOCK"
    flock -w 5 8
}

release_state_lock() {
    flock -u 8 2>/dev/null || true
}

# Globals populated by load_state: history[], cursor, pending_target,
# pending_origin, and pending_at.
load_state() {
    local first id old_cursor old_target old_origin old_at
    history=()
    cursor=0
    pending_target=-
    pending_origin=-
    pending_at=0
    old_cursor=0
    old_target=-
    old_origin=-
    old_at=0

    [[ -r "$STATE_FILE" ]] || return 0
    first=$(head -n 1 "$STATE_FILE" 2>/dev/null || true)

    if [[ "$first" == cursor\ * ]]; then
        {
            read -r _ old_cursor || true
            read -r _ old_target old_origin old_at || true
            [[ "$old_cursor" =~ ^[0-9]+$ ]] && cursor=$old_cursor
            [[ "$old_target" =~ ^[0-9]+$ ]] && pending_target=$old_target
            [[ "$old_origin" =~ ^[0-9]+$ ]] && pending_origin=$old_origin
            [[ "$old_at" =~ ^[0-9]+$ ]] && pending_at=$old_at
            while IFS= read -r id; do
                add_history "$id"
            done
        } <"$STATE_FILE"
    else
        # Migrate the original plain one-ID-per-line format.
        while IFS= read -r id; do
            add_history "$id"
        done <"$STATE_FILE"
    fi

    (( cursor < ${#history[@]} )) || cursor=0
}

add_history() {
    local id="$1" existing
    [[ "$id" =~ ^[0-9]+$ ]] || return 0
    for existing in "${history[@]}"; do
        [[ "$existing" == "$id" ]] && return 0
    done
    ((${#history[@]} < MAX_HISTORY)) && history+=("$id")
}

write_state() {
    local tmp id
    tmp=$(mktemp "${STATE_FILE}.XXXXXX") || return 1
    {
        printf 'cursor %s\n' "$cursor"
        printf 'pending %s %s %s\n' "$pending_target" "$pending_origin" "$pending_at"
        for id in "${history[@]}"; do
            printf '%s\n' "$id"
        done
    } >"$tmp" && mv -f "$tmp" "$STATE_FILE"
}

record_current() {
    local current="$1" timestamp old_id index
    [[ "$current" =~ ^[0-9]+$ ]] || return 0
    with_state_lock || return 0
    load_state
    timestamp=$(now)

    # Ignore the origin/target events generated by our own focus command.
    # This matters because cross-workspace focus can emit multiple events.
    if [[ "$pending_target" =~ ^[0-9]+$ ]] &&
        (( timestamp - pending_at <= PENDING_TTL )) &&
        { [[ "$current" == "$pending_target" ]] || [[ "$current" == "$pending_origin" ]]; }; then
        index=0
        for old_id in "${history[@]}"; do
            [[ "$old_id" == "$current" ]] && { cursor=$index; break; }
            ((index++))
        done
        write_state
        release_state_lock
        return 0
    fi

    # A normal focus change starts a fresh traversal at the top of the stack.
    local old_history=("${history[@]}")
    history=("$current")
    for old_id in "${old_history[@]}"; do
        add_history "$old_id"
    done
    cursor=0
    pending_target=-
    pending_origin=-
    pending_at=0
    write_state
    release_state_lock
}

daemon() {
    # Only one listener, including after Sway config reloads.
    exec 9>"$DAEMON_LOCK"
    flock -n 9 || exit 0

    record_current "$(current_container)"
    while swaymsg -t subscribe -m '["window", "workspace"]' 2>/dev/null |
        while IFS= read -r _event; do
            record_current "$(current_container)"
        done
    do
        # Reconnect if Sway IPC is temporarily unavailable.
        sleep 1
    done
}

navigate() {
    local direction="$1" current target target_index current_index old_id timestamp
    current=$(current_container)
    [[ "$current" =~ ^[0-9]+$ ]] || return 0

    with_state_lock || return 0
    load_state

    # Remove closed windows before selecting a target.
    local live_history=()
    for old_id in "${history[@]}"; do
        container_exists "$old_id" && live_history+=("$old_id")
    done
    history=("${live_history[@]}")

    # If the daemon has not observed the current focus yet, seed/fix the list.
    current_index=-1
    for old_id in "${history[@]}"; do
        ((current_index++))
        [[ "$old_id" == "$current" ]] && break
    done
    if (( current_index < 0 || current_index >= ${#history[@]} || history[current_index] != current )); then
        history=("$current" "${history[@]}")
        ((${#history[@]} > MAX_HISTORY)) && history=("${history[@]:0:MAX_HISTORY}")
        current_index=0
    fi

    if [[ "$direction" == prev ]]; then
        target_index=$((current_index + 1))
    else
        target_index=$((current_index - 1))
    fi

    if (( target_index < 0 || target_index >= ${#history[@]} )); then
        cursor=$current_index
        pending_target=-
        pending_origin=-
        pending_at=0
        write_state
        release_state_lock
        return 0
    fi

    target=${history[target_index]}
    timestamp=$(now)
    cursor=$target_index
    pending_target=$target
    pending_origin=$current
    pending_at=$timestamp
    write_state
    release_state_lock

    if ! swaymsg "[con_id=$target] focus" >/dev/null 2>&1; then
        # Do not leave a failed navigation request affecting later events.
        with_state_lock && {
            load_state
            if [[ "$pending_target" == "$target" ]]; then
                pending_target=-
                pending_origin=-
                pending_at=0
                write_state
            fi
            release_state_lock
        }
    fi
}

case "${1:-}" in
    --daemon) daemon ;;
    --prev) navigate prev ;;
    --next) navigate next ;;
    *)
        printf 'usage: %s --daemon|--prev|--next\n' "$0" >&2
        exit 2
        ;;
esac
